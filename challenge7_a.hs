splitColumns number text = map filterColumn [0..number]
    where filterColumn n = map snd $ filter nthCharacter $ zip [0..] text
            where nthCharacter (i, _) = (i `mod` number) == n

subtractCharacter k l = chr $ ord 'A' + (ord l - ord k) `mod` 26

guessByFrequency guess text =
    subtractCharacter 'E' $ snd $ head $
        drop guess $ reverse $ sort $ map (\l -> (length l, head l)) $
        group $ sort $ text

decodeWith = zipWith subtractCharacter . cycle

guessEachColumnByFrequency guesses key_length = zipWith guessByFrequency guesses . splitColumns key_length

