def decrypt_vignere(ciphertext, key):
    ciphertext = ciphertext.replace(" ", "").upper()
    key = key.replace(" ", "").upper()
    plaintext = ""
    keyn = 0
    for letter in ciphertext:
        #plaintext += (letter - key[keyn]) % 26
        plaintext += chr(65+(ord(letter)-64 + (ord(key[keyn])-64)) % 26)
        keyn += 1
        if keyn >= len(key):
            keyn = 0
    return plaintext


